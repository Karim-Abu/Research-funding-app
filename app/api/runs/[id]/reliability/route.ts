import { forwardToBridge } from "@/lib/bridge"

// GET/POST /api/runs/{id}/reliability — beta-internal MAS reliability pass + summary (M9K).
export async function GET(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params
  return forwardToBridge(request, `/runs/${encodeURIComponent(id)}/reliability`)
}

export async function POST(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params
  return forwardToBridge(request, `/runs/${encodeURIComponent(id)}/reliability`)
}
